-- 0013_vehicle_profiles.sql
-- Public vehicle compatibility database. Powers:
--   /supported-vehicles        (public landing page, anon read)
--   /admin/vehicle-database    (Master Portal management, authenticated write)
-- Content is EDUCATIONAL reference material for installers — always rendered
-- with an at-your-own-risk disclaimer.

create table if not exists public.vehicle_profiles (
  id          uuid primary key default gen_random_uuid(),
  slug        text not null unique,
  make        text not null,
  model       text not null,
  variant     text,
  year_from   int,
  year_to     int,                  -- null = still in production
  category    text not null check (category in
                ('kei','compact','sedan','suv','pickup','van','minibus','bus','truck','other')),
  market      text,                 -- 'JDM import', 'EU', 'CN', 'US', 'ZA', 'ZIM common'
  voltage     text not null default '12V' check (voltage in ('12V','24V','hybrid','EV')),
  difficulty  text not null default 'moderate' check (difficulty in ('easy','moderate','advanced')),
  hybrid_or_ev boolean not null default false,
  canbus      boolean not null default false,
  fusebox_notes    text,            -- where constant + ACC power is found
  cutoff_notes     text,            -- recommended engine-cut approach + warnings
  fuel_sensor_notes text,
  accessories_notes text,           -- RFID driver ID, dashcam, cabin cam, alarm
  install_notes    text,            -- general educational guidance
  zimbabwe_notes   text,            -- local-market remarks (import prevalence etc.)
  is_published boolean not null default true,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create index if not exists vehicle_profiles_make_idx     on public.vehicle_profiles (make);
create index if not exists vehicle_profiles_category_idx on public.vehicle_profiles (category);

alter table public.vehicle_profiles enable row level security;

drop policy if exists vehicle_profiles_public_read on public.vehicle_profiles;
create policy vehicle_profiles_public_read on public.vehicle_profiles
  for select using (is_published = true);

-- v1: any signed-in user may curate; tighten to an admin role claim later.
drop policy if exists vehicle_profiles_auth_write on public.vehicle_profiles;
create policy vehicle_profiles_auth_write on public.vehicle_profiles
  for all to authenticated using (true) with check (true);

